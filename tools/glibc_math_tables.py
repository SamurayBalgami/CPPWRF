#!/usr/bin/env python3
"""Data of glibc's libm and libmvec (Debian 13, glibc 2.41, x86-64) as a C++ header for src/core/glibc_math.hpp.

  python3 tools/glibc_math_tables.py LIBM LIBM_DEBUG LIBMVEC LIBMVEC_DEBUG > src/core/glibc_math_tables.hpp

LIBM / LIBMVEC: /lib/x86_64-linux-gnu/libm.so.6 and libmvec.so.1 of the machine that made WRF's references (Debian 13,
glibc 2.41-12); LIBM_DEBUG / LIBMVEC_DEBUG: their debug files (symbols of the internal functions and tables), e.g.
  curl -o libm.debug https://debuginfod.debian.net/buildid/$(readelf -n LIBM | awk '/Build ID/ {print $3}')/debuginfo

src/core/glibc_math.hpp re-implements the libm functions that WRF and CPPWRF's CPU build call (the variants glibc's
ifuncs select on a CPU with FMA and AVX2, e.g. __ieee754_exp_fma) and libmvec's 2-lane SSE4 functions instruction by
instruction from their machine code (objdump -d of the libraries: Debian's 2.41 differs from the 2.41 tarball, e.g. in
the layout of __exp_data), so that the CUDA FP64 build computes what glibc computes. The tables they read are copied
here bit for bit, each as the whole object of the library (64-bit words, little-endian), so that the code indexes them
by the byte offsets of the machine code. The build IDs of the libraries are checked against the ones the
functions were transcribed from.
"""
import struct
import subprocess
import sys

BUILD_IDS = {"libm": "befc0308f899f79b901d4e738992787368cf70f7", "libmvec": "4820e45820b4fa640201630c1cabc1b3df59affb"}
# (library, symbol or "ADDRESS:SIZE" for a static object without a symbol (the address the machine code reads), C++ name)
OBJECTS = [
    ("libm", "__exp_data", "kExpData"),
    ("libm", "__log_data", "kLogData"),
    ("libm", "__pow_log_data", "kPowLogData"),
    ("libmvec", "__svml_dexp_data", "kSvmlExpData"),
    ("libmvec", "__svml_dpow_data", "kSvmlPowData"),
    ("libm", "0xdc360:13496", "kAtanCij"),  # cij[241][7] of s_atan.c (uatan.tbl), read by __atan_fma
    ("libm", "__sincostab", "kSinCosTab"),  # sincostab.c, read by __sin_fma and __cos_fma
    ("libm", "0xbb140:600", "kBranredToverp"),  # toverp[75] of branred.h (2/pi in base 2^24), read by __branred
    # asncs (asincos.tbl), inroot (root.tbl) and powtwo (powtwo.tbl) as read by __ieee754_asin_fma / __ieee754_acos_fma
    ("libm", "0xcd4e0:20544", "kAsnCs"),
    ("libm", "0xcd0e0:1024", "kInRoot"),
    ("libm", "0xcd000:224", "kPowTwo"),
    ("libm", "0xe10a0:5952", "kTanXfg"),  # xfg[186][4] of utan.tbl (static in __tan), read by __tan_fma
    ("libmvec", "__svml_d_trig_data", "kSvmlTrigData"),  # svml_d_trig_data.S, read by _ZGVbN2v_sin/cos_sse4
    # __svml_datan_data_internal_avx512 of svml_d_atan2_core_sse4.S (0x300 bytes) and its .FLT_11 index mask after it
    ("libmvec", "0x46d90:784", "kSvmlAtanData"),
]


def build_id(path):
    out = subprocess.run(["readelf", "-n", path], capture_output=True, text=True, check=True).stdout
    for line in out.splitlines():
        if "Build ID:" in line:
            return line.split(":", 1)[1].strip()
    sys.exit(f"{path}: no build ID")


class Elf:
    def __init__(self, path):
        self.data = open(path, "rb").read()
        d = self.data
        phoff = struct.unpack_from("<Q", d, 0x20)[0]
        phentsize, phnum = struct.unpack_from("<HH", d, 0x36)
        self.segs = []
        for i in range(phnum):
            p_type, _, p_offset, p_vaddr, _, p_filesz = struct.unpack_from("<IIQQQQ", d, phoff + i * phentsize)
            if p_type == 1:  # PT_LOAD
                self.segs.append((p_vaddr, p_offset, p_filesz))

    def read(self, va, n):
        for v, o, s in self.segs:
            if v <= va and va + n <= v + s:
                return self.data[o + va - v:o + va - v + n]
        sys.exit(f"0x{va:x}: not in the file")


def symbols(debug):
    out = subprocess.run(["nm", "-S", debug], capture_output=True, text=True, check=True).stdout
    syms = {}
    for line in out.splitlines():
        p = line.split()
        if len(p) == 4:
            syms.setdefault(p[3], (int(p[0], 16), int(p[1], 16)))
    return syms


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    libs = {"libm": (sys.argv[1], sys.argv[2]), "libmvec": (sys.argv[3], sys.argv[4])}
    elf, syms = {}, {}
    for k, (lib, dbg) in libs.items():
        for p in (lib, dbg):
            if build_id(p) != BUILD_IDS[k]:
                sys.exit(f"{p}: build ID {build_id(p)}, the functions were transcribed from {BUILD_IDS[k]}")
        elf[k] = Elf(lib)
        syms[k] = symbols(dbg)
    out = ["#pragma once",
           "// GENERATED by tools/glibc_math_tables.py from Debian 13's glibc 2.41 (x86-64); do not edit.",
           f"// libm.so.6 build ID {BUILD_IDS['libm']}, libmvec.so.1 build ID {BUILD_IDS['libmvec']}.",
           "// Each table is the whole object of the library as 64-bit words; src/core/glibc_math.hpp reads it at the",
           "// byte offsets of the machine code (word = offset / 8). Device copies in namespace dev (member v).",
           "#include <cstdint>", ""]
    defs = []
    out.append("namespace cppwrf::glibc_tables {")
    for lib, sym, name in OBJECTS:
        if ":" in sym:
            va, size = (int(v, 0) for v in sym.split(":"))
        else:
            va, size = syms[lib][sym]
        if size % 8:
            sys.exit(f"{sym}: size {size} is not a multiple of 8")
        words = struct.unpack(f"<{size // 8}Q", elf[lib].read(va, size))
        out.append(f"// {sym} ({lib}, {size} bytes)")
        out.append(f"inline constexpr std::uint64_t {name}[{len(words)}] = {{")
        for i in range(0, len(words), 4):
            out.append("    " + ", ".join(f"0x{w:016x}ull" for w in words[i:i + 4]) + ",")
        out.append("};")
        defs.append((name, len(words)))
    out.append("}  // namespace cppwrf::glibc_tables")
    out.append("#if defined(__CUDACC__)")
    out.append("namespace cppwrf::glibc_tables::dev {  // device copies (constant-initialised from the host tables)")
    out.append("template <int N>")
    out.append("struct Words {")
    out.append("  std::uint64_t v[N];")
    out.append("};")
    out.append("template <int N>")
    out.append("constexpr Words<N> words(const std::uint64_t (&a)[N]) {")
    out.append("  Words<N> w{};")
    out.append("  for (int i = 0; i < N; ++i) w.v[i] = a[i];")
    out.append("  return w;")
    out.append("}")
    for name, n in defs:
        out.append(f"static __device__ const Words<{n}> {name} = words(::cppwrf::glibc_tables::{name});")
    out.append("}  // namespace cppwrf::glibc_tables::dev")
    out.append("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
